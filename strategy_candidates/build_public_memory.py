"""Build a standalone Blocker correction from the exact archived original.

This does not modify the original tester or any already registered study arm.
Only public contradictions to inferred Shield events are removed. Ambiguous
cooldowns still use the original heuristic; no hidden action is reconstructed.
"""
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ORIGINAL_SHA = '1bb70109a75e2880bfdf3ac9b6fd8e368b0f3d02b9a3e65de53cef0defa505e5'

OLD_INFERENCE = '''            o = own[q]
            if o and o != j and not pfrz[o] and tp - self.last_shield[o] > 4:
                shs.add(o)
            else:
                shs.add(j)
'''

NEW_INFERENCE = '''            # Catches happen before ownership work, on the prior owner's land.
            o = pown[q]
            owner_possible = bool(o and o != j and not pfrz[o]
                                  and not moved[o]
                                  and tp - self.last_shield[o] > 4)
            if o == me and self.last != "SHIELD":
                owner_possible = False
            # An eligible own STAY would also have been caught by that owner.
            # A blocked move is a STAY; displacement and own SHIELD are not.
            if (owner_possible and not pfrz[me] and not moved[me]
                    and self.last != "SHIELD" and not frz[me]
                    and pown[pos[me]] == o):
                owner_possible = False
            if owner_possible:
                shs.add(o)
            else:
                shs.add(j)
'''

OLD_PROGRESS = '            elif home[P] or o in shs:\n'
NEW_PROGRESS = '''            # An actual defending Shield would already have frozen an eligible
            # own STAY. A guessed Shield must not suppress observed work.
            elif home[P]:
'''


def build():
    body = (ROOT/'tester_bots/blocker.py').read_bytes()
    if hashlib.sha256(body).hexdigest() != ORIGINAL_SHA:
        raise ValueError('The archived Blocker source changed')
    text = body.decode('utf8')
    for before, after in ((OLD_INFERENCE, NEW_INFERENCE), (OLD_PROGRESS, NEW_PROGRESS)):
        if text.count(before) != 1:
            raise ValueError('Expected exactly one pinned correction site')
        text = text.replace(before, after, 1)
    header = ('# Unpromoted public-memory correction. Generated by build_public_memory.py.\n'
              '# Parent SHA256: '+ORIGINAL_SHA+'\n')
    return (header+text).encode('utf8')


def main():
    target = ROOT/'strategy_candidates/blocker_public_memory.py'
    body = build()
    target.write_bytes(body)
    print(hashlib.sha256(body).hexdigest())


if __name__ == '__main__':
    main()
