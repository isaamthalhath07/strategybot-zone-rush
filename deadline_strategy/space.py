"""Exact published f5 public-memory structure plus the fixed Blocker numeric loci.

Only source bytes are produced. This module never loads a policy, plays a game,
selects parents, qualifies a runtime, accepts evidence or grants any game credit.
"""
import ast
from pathlib import Path

from evolution_templates.space import TemplateSpace, literal_sites, sha
from strategy_candidates import build_public_memory as builder

ROOT = Path(__file__).resolve().parents[1]
FORMAT = 'zone-rush-exact-public-memory-blocker-family/1'
FAMILY = 'public-memory-blocker'
STRATEGY_FAMILY = 'blocker'
TEMPLATE_SHA256 = 'f5e870cd8bb56024c579d1251943c656daf62d2652c5eba44aee530ba1160405'
DEPENDENCIES = {
    'evolution_templates/__init__.py': 'ed42d43929bb9eb525484e62a937a3d598824d3c151ab48a35bd24baeb03e381',
    'evolution_templates/space.py': 'bce6dd1fa5950a8752182ce4c70e17ea10d74245a7fe650cc735b3483b2ae041',
    'strategy_candidates/build_public_memory.py': 'd4a421c719c0eb2e69ce786fdc5c53042b475e50509bc7104f1b0faa9e1d35e4',
    'strategy_candidates/__init__.py': 'a8d048b258b644cb7a819b5d402328adf8345fc8ca43b2714ce371f5ac0b75e4',
    'strategy_candidates/blocker_public_memory.py': TEMPLATE_SHA256,
    'tester_bots/blocker.py': '1bb70109a75e2880bfdf3ac9b6fd8e368b0f3d02b9a3e65de53cef0defa505e5',
}


def source_pins():
    result = {name:sha((ROOT/name).read_bytes()) for name in DEPENDENCIES}
    if result != DEPENDENCIES:
        raise ValueError('QUARANTINED: public-memory template or exact numeric exporter changed')
    for name in ('deadline_strategy/__init__.py','deadline_strategy/space.py'):
        result[name] = sha((ROOT/name).read_bytes())
    return result


class PublicMemoryTemplateSpace:
    """Twelve-locus canonical numeric exports of the fixed f5 structural template.

    Numerical crossover requires this structural template to be chosen first.
    A caller cannot cross original/fixed structures implicitly through genes.
    """
    family = FAMILY
    strategy_family = STRATEGY_FAMILY
    template_sha256 = TEMPLATE_SHA256

    def __init__(self):
        self._pins = source_pins()
        self._numeric = TemplateSpace('original-blocker')
        self._body = builder.build()
        if sha(self._body) != TEMPLATE_SHA256:
            raise ValueError('QUARANTINED: builder no longer creates exact published f5 bytes')

    @property
    def bounds(self):
        return self._numeric.bounds

    @property
    def defaults(self):
        return self._numeric.defaults

    def _guard(self):
        if (source_pins() != self._pins or sha(self._body) != TEMPLATE_SHA256
                or self.family != FAMILY or self.strategy_family != STRATEGY_FAMILY
                or self.template_sha256 != TEMPLATE_SHA256):
            raise ValueError('QUARANTINED: fixed public-memory structure or source closure changed')

    def validate(self,genes):
        self._guard()
        return self._numeric.validate(genes)

    def export(self,genes):
        self._guard()
        # The frozen numeric exporter verifies every original non-locus byte.
        body = self._numeric.export(genes)
        text = body.decode('utf8')
        for before,after in ((builder.OLD_INFERENCE,builder.NEW_INFERENCE),
                             (builder.OLD_PROGRESS,builder.NEW_PROGRESS)):
            if text.count(before) != 1:
                raise ValueError('Expected one exact public-memory correction site')
            text = text.replace(before,after,1)
        header = ('# Unpromoted public-memory correction. Generated by build_public_memory.py.\n'
                  '# Parent SHA256: '+builder.ORIGINAL_SHA+'\n')
        result = (header+text).encode('utf8')
        ast.parse(result)
        return result

    def inspect_export(self,body):
        self._guard()
        if type(body) is not bytes or len(body) > len(self._body)+2048:
            raise ValueError('Bounded standalone public-memory source bytes required')
        sites = literal_sites(body,self.bounds)
        genes = self.validate({key:site[2] for key,site in sites.items()})
        if body != self.export(genes):
            raise ValueError('Source changed outside exact canonical f5 numeric replacements')
        return genes

    def mutate(self,parent,seed,scale=0.06,max_changes=3):
        self._guard()
        return self._numeric.mutate(parent,seed,scale,max_changes)

    def crossover(self,first,second,seed):
        self._guard()
        return self._numeric.crossover(first,second,seed)

    def description(self):
        self._guard()
        result = self._numeric.description()
        result.update(format=FORMAT,family=FAMILY,strategy_family=STRATEGY_FAMILY,
            template_sha256=TEMPLATE_SHA256,parent_template_sha256=builder.ORIGINAL_SHA,
            structural_change='exact published f5 prior-ownership and public-contradiction correction; own progress from public work evidence',
            source_sha256=source_pins(),runtime_qualified=False,playing_strength_tested=False,
            admission_authority=False,primary_credit=0,bmcts_audits=0,promotion_credit=0)
        return result
