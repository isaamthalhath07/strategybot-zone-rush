class _world_Game(object):
    __slots__ = ('base', 'owner', 'upg', 'home', 'pos', 'frozen', 'cd', 'prog', 'score', 'income', 'turn', 'token', 'max_turns', 'rules')

    def __init__(self, base=None, max_turns=80, rules=None, start_token=1):
        self.base = list(base if base is not None else _world_make_map(canonical=True))
        self.owner = [0] * _world_NC
        self.upg = [0] * _world_NC
        self.home = [0] * _world_NC
        self.pos = [0] * 4
        self.frozen = [0] * 4
        self.cd = [0] * 4
        self.prog = [0] * 4
        self.score = [0] * 4
        self.income = [0] * 4
        self.turn = 1
        self.max_turns = max_turns
        self.token = start_token
        self.rules = dict(_world_RULES)
        if rules:
            self.rules.update(rules)
        for seat, cell in _world_CORNERS.items():
            self.home[cell] = seat
            self.owner[cell] = seat
            self.pos[seat - 1] = cell
            self.income[seat - 1] = self.base[cell]

    def clone(self):
        g = _world_Game.__new__(_world_Game)
        g.base = self.base
        g.owner = self.owner[:]
        g.upg = self.upg[:]
        g.home = self.home
        g.pos = self.pos[:]
        g.frozen = self.frozen[:]
        g.cd = self.cd[:]
        g.prog = self.prog[:]
        g.score = self.score[:]
        g.income = self.income[:]
        g.turn = self.turn
        g.token = self.token
        g.max_turns = self.max_turns
        g.rules = self.rules
        return g

    def legal(self, i):
        if self.frozen[i] > 0:
            return ['STAY']
        out = ['STAY']
        r, c = divmod(self.pos[i], _world_N)
        if r > 0:
            out.append('NORTH')
        if r < _world_N - 1:
            out.append('SOUTH')
        if c > 0:
            out.append('WEST')
        if c < _world_N - 1:
            out.append('EAST')
        if self.cd[i] == 0:
            out.append('SHIELD')
        return out

    def board_view(self):
        occ = [0] * _world_NC
        frz = [False] * _world_NC
        for i in range(4):
            occ[self.pos[i]] = i + 1
            if self.frozen[i] > 0:
                frz[self.pos[i]] = True
        bd = []
        for r in range(_world_N):
            row = []
            for c in range(_world_N):
                p = r * _world_N + c
                row.append(_world_Cell(occ[p], self.owner[p], bool(self.upg[p]), bool(self.home[p]), frz[p], self.base[p]))
            bd.append(row)
        return bd

    def views(self):
        bd = self.board_view()
        return [_world_View(bd, i + 1, self.token == i + 1, self.legal(i)) for i in range(4)]

    def step(self, actions):
        """actions[i] is seat i+1's chosen action string. Resolves one full turn."""
        R = self.rules
        eff = [None] * 4
        for i in range(4):
            if self.frozen[i] > 0:
                eff[i] = 'STAY'
                continue
            a = actions[i]
            if a == 'SHIELD':
                eff[i] = 'STAY' if self.cd[i] > 0 else 'SHIELD'
            elif a in _world_MOVES:
                r, c = divmod(self.pos[i], _world_N)
                if a == 'NORTH' and r == 0 or (a == 'SOUTH' and r == _world_N - 1) or (a == 'WEST' and c == 0) or (a == 'EAST' and c == _world_N - 1):
                    eff[i] = 'STAY'
                else:
                    eff[i] = a
            else:
                eff[i] = 'STAY'
        closed = set(self.pos)
        intents = {}
        for i in range(4):
            if eff[i] in _world_MOVES:
                t = self.pos[i] + _world_MOVES[eff[i]]
                if t in closed:
                    eff[i] = 'STAY'
                else:
                    intents.setdefault(t, []).append(i)
        for t, seats in intents.items():
            if len(seats) == 1:
                w = seats[0]
            else:
                own = [s for s in seats if self.owner[t] == s + 1]
                if own:
                    w = own[0]
                else:
                    w, best = (seats[0], 99)
                    for s in seats:
                        rank = (s + 1 - self.token) % 4
                        if rank < best:
                            best, w = (rank, s)
                for s in seats:
                    if s != w:
                        eff[s] = 'STAY' if R['lost_contest_is_stay'] else 'BLOCKED'
            self.pos[w] = t
            self.prog[w] = 0
        for i in range(4):
            if eff[i] == 'SHIELD':
                self.prog[i] = 0
        shielders = [i for i in range(4) if eff[i] == 'SHIELD']
        caught = [False] * 4
        newfrozen = [0] * 4
        for s in shielders:
            seat = s + 1
            got = []
            for j in range(4):
                if j == s or self.frozen[j] > 0:
                    continue
                if R['catch_requires_stay'] and eff[j] != 'STAY':
                    continue
                if self.owner[self.pos[j]] == seat:
                    got.append(j)
            if got:
                for j in got:
                    caught[j] = True
                    newfrozen[j] = 2
                    self.prog[j] = 0
            else:
                newfrozen[s] = 2
        shielded_seats = set((s + 1 for s in shielders))
        for i in range(4):
            if eff[i] != 'STAY' or caught[i]:
                continue
            if self.frozen[i] > 0 and (not R['frozen_stay_counts']):
                continue
            p = self.pos[i]
            seat = i + 1
            o = self.owner[p]
            if o == seat:
                if self.upg[p]:
                    continue
                if self.home[p] == seat and (not R['home_upgradable']):
                    continue
                self.prog[i] += 1
                if self.prog[i] >= 3:
                    self.upg[p] = 1
                    self.prog[i] = 0
                    self.income[i] += self.base[p]
            elif o == 0:
                self.prog[i] += 1
                if self.prog[i] >= 1:
                    self.owner[p] = seat
                    self.income[i] += self.base[p]
                    if R['claim_resets_progress']:
                        self.prog[i] = 0
            else:
                if self.home[p] or o in shielded_seats:
                    continue
                needed = 3 if self.upg[p] else 1
                self.prog[i] += 1
                if self.prog[i] >= needed:
                    lvl = 2 if self.upg[p] else 1
                    self.score[i] += 8 * self.base[p] * lvl
                    self.income[o - 1] -= self.base[p] * lvl
                    self.owner[p] = seat
                    self.upg[p] = 0
                    self.income[i] += self.base[p]
                    if R['claim_resets_progress']:
                        self.prog[i] = 0
        for i in range(4):
            self.score[i] += self.income[i]
        for i in range(4):
            if self.frozen[i] > 0:
                self.frozen[i] -= 1
            if newfrozen[i]:
                self.frozen[i] = newfrozen[i]
                self.prog[i] = 0
        for i in range(4):
            if i in shielders:
                self.cd[i] = 4
            elif self.cd[i] > 0:
                self.cd[i] -= 1
        self.token = self.token % 4 + 1
        self.turn += 1
        return eff

    def over(self):
        return self.turn > self.max_turns

    def cells_owned(self, i):
        seat = i + 1
        n = 0
        for p in range(_world_NC):
            if self.owner[p] == seat:
                n += 1
        return n

    def places(self, round_number=1, round1_ranks=None):
        """1-based mean place per seat under the selected competition round.

        Round 1 compares final scores only (rulebook 3.2): equal scores are
        draws regardless of cells. Round 2 first breaks score ties by cells
        (5.3). Pool games then share the remaining ties. For a Round 2
        semi-final or final, supply each seat's Round 1 rank, lower being
        better, to apply the last knockout tiebreak.
        """
        if round_number not in (1, 2):
            raise ValueError('round_number must be 1 or 2')
        if round1_ranks is not None:
            if round_number != 2 or len(round1_ranks) != 4:
                raise ValueError('round1_ranks requires Round 2 and four seat ranks')
        key = [(-self.score[i],) for i in range(4)]
        if round_number == 2:
            key = [key[i] + (-self.cells_owned(i),) for i in range(4)]
            if round1_ranks is not None:
                key = [key[i] + (round1_ranks[i],) for i in range(4)]
        order = sorted(range(4), key=lambda i: key[i])
        place = [0.0] * 4
        i = 0
        while i < 4:
            j = i
            while j + 1 < 4 and key[order[j + 1]] == key[order[i]]:
                j += 1
            shared = (i + 1 + j + 1) / 2.0
            for k in range(i, j + 1):
                place[order[k]] = shared
            i = j + 1
        return place

def _world_play(bots, base=None, max_turns=80, rules=None, start_token=1):
    """bots[i] is a callable act(view) for seat i+1. Returns the finished Game."""
    g = _world_Game(base=base, max_turns=max_turns, rules=rules, start_token=start_token)
    while not g.over():
        vs = g.views()
        acts = []
        for i in range(4):
            try:
                a = bots[i](vs[i])
            except Exception:
                a = 'STAY'
            if a not in vs[i].legal_actions:
                a = 'STAY'
            acts.append(a)
        g.step(acts)
    return g

