    def _plan_walk(self, owner, upg, base, home, occ, frz, seat, me, R, kappa, care):
        base_action = _base_Agent._plan_walk(self, owner, upg, base, home, occ, frz, seat, me, R, kappa, care)
        if not self.feature:
            return base_action
        if self.job is not None:
            p, level = self.job
            completed = owner[p] == seat and (level == 1 or upg[p])
