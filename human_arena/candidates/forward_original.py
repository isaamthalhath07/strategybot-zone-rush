def _bounded_proposals(player, owner, upg, base, home, occ, seat, me, R, kappa, care, deadline):
    if _bounded_time.perf_counter() >= deadline:
        return []
    candidates = player._candidates(owner, upg, base, home, occ, seat, me, R, care)
    beam = [(0.0, me, 0, frozenset(), ())]
    best = {}
    for depth in range(6):
        nxt = []
        for value, pos, elapsed, visited, path in beam:
            if _bounded_time.perf_counter() >= deadline:
                break
            for _, _, p, kind, v, need in candidates:
                if p in visited:
                    continue
                travel = _base_DIST[pos][p]
                if p == me and elapsed and player.tr.prog[seat - 1]:
                    need = 4 if kind == 3 else 3 if kind == 1 or (kind == 2 and upg[p]) else 1
                arrival = elapsed + travel
                finished = arrival + need
                if finished > min(40, R):
                    continue
                gain = player._work_gain(p, kind, v, need, arrival, owner, upg, occ, seat, R, kappa, care, travel)
                if gain is None:
                    continue
                level = 0 if kind == 4 else 2 if kind in (1, 3) else 1
                route = path + ((p, level),)
                score = value + gain
                first = route[0][0]
                if first not in best or score > best[first][0]:
                    best[first] = (score, route)
                nxt.append((score, p, finished, visited | {p}, route))
        if not nxt:
            break
        beam = sorted(nxt, key=lambda x: x[0], reverse=True)[:32]
    ordered = sorted(best, key=lambda p: best[p][0], reverse=True)
    if player.plan_target in ordered:
        ordered.remove(player.plan_target)
        ordered.insert(0, player.plan_target)
    return [best[p][1] for p in ordered[:6]]

def _bounded_simulate(initial, seat, route, profiles, particle, horizon, deadline, first_action):
    game = initial.clone()
    route = list(route)
    targets = [None] * 4
    own_profile = (0.91, 1.58, 1.4, 0.0, 1.0, 0.75)
    blocked = 0
    for elapsed in range(min(horizon, 81 - game.turn)):
        if _bounded_time.perf_counter() >= deadline:
            return None
        actions = []
        for j in range(4):
            if _bounded_time.perf_counter() >= deadline:
                return None
            draw = _roll_noise(particle, game.turn, j)
            if j != seat:
                action, targets[j] = _model_action(game, j, profiles[j], targets[j], draw)
            elif elapsed == 0:
                action = first_action
            elif game.frozen[j]:
                action = 'STAY'
            elif _model_should_shield(game, j, own_profile[5], draw):
                action = 'SHIELD'
            else:
                while route:
                    p, level = route[0]
                    complete = level > 0 and game.owner[p] == j + 1 and (level == 1 or game.upg[p])
                    if complete or (game.home[p] and game.owner[p] != j + 1):
                        route.pop(0)
                    else:
                        break
                if route:
                    goal = route[0][0]
                    action = _model_step(game, j, goal)
                    if route[0][1] == 0 and game.pos[j] == goal:
                        route.pop(0)
                    if action == 'STAY' and game.pos[j] != goal:
                        blocked += 1
                        if blocked >= 2:
                            route.pop(0)
                            blocked = 0
                    else:
                        blocked = 0
                else:
                    action, targets[j] = _model_action(game, j, own_profile, targets[j], draw)
            actions.append(action)
        game.step(actions)
    tail = max(0, 81 - game.turn)
    projected = [s + tail * i for s, i in zip(game.score, game.income)]
    own = projected[seat]
    pw = sum((1 / (1 + _bounded_math.exp(max(-20, min(20, (projected[j] - own) / 180)))) for j in range(4) if j != seat))
    return (own, pw, [])

