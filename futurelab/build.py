"""Build a readable single-file submission without dynamic execution/imports.

Project modules are flattened with distinct global prefixes. The original v8
benchmark stays byte-identical, keeping old experiment provenance reproducible.
"""
import argparse
import ast
import hashlib
import json
import symtable
from pathlib import Path

from futurelab.protocol import REGISTRY


MODULES = (
    ("bot","bot.py","_base_"),
    ("engine","engine.py","_world_"),
    ("botlib","botlib.py","_public_"),
    ("futurelab.models","futurelab/models.py","_model_"),
    ("futurelab.rollout","futurelab/rollout.py","_roll_"),
    ("futurelab.agent","futurelab/agent.py","_ahead_"),
    ("futurelab.alternatives","futurelab/alternatives.py","_control_"),
    ("futurelab.bounded","futurelab/bounded.py","_bounded_"),
)
PREFIX = {name:prefix for name,file,prefix in MODULES}


class Flatten(ast.NodeTransformer):
    def __init__(self,source,filename,prefix):
        table = symtable.symtable(source,filename,"exec")
        self.names = {s.get_name():prefix+s.get_name() for s in table.get_symbols()
                      if s.is_assigned() or s.is_imported() or s.is_namespace()}
        self.modules = {}
        self.prefix = prefix

    def visit_Import(self,node):
        kept = []
        for alias in node.names:
            local = alias.asname or alias.name
            if alias.name in PREFIX:
                self.modules[local] = PREFIX[alias.name]
            else:
                kept.append(ast.alias(name=alias.name,asname=self.names[local]))
        return ast.Import(names=kept) if kept else None

    def visit_ImportFrom(self,node):
        kept = []
        for alias in node.names:
            local = alias.asname or alias.name
            target = (node.module+"."+alias.name) if node.module else alias.name
            if target in PREFIX:
                self.modules[local] = PREFIX[target]
            elif node.module in PREFIX:
                self.names[local] = PREFIX[node.module]+alias.name
            else:
                kept.append(ast.alias(name=alias.name,asname=self.names[local]))
        return ast.ImportFrom(module=node.module,names=kept,level=0) if kept else None

    def visit_Attribute(self,node):
        if isinstance(node.value,ast.Name) and node.value.id in self.modules:
            return ast.copy_location(ast.Name(id=self.modules[node.value.id]+node.attr,ctx=node.ctx),node)
        return self.generic_visit(node)

    def visit_Name(self,node):
        if node.id in self.modules:
            raise AssertionError("module used as a first-class value; cannot flatten safely: "+node.id)
        return ast.copy_location(ast.Name(id=self.names.get(node.id,node.id),ctx=node.ctx),node)

    def visit_arg(self,node):
        # Preserve a lexical argument shadowing a prefixed global. All Names in
        # that scope receive the same prefix. These sources have no keyword
        # calls using any such shadowed argument; equivalence tests check output.
        node.arg = self.names.get(node.arg,node.arg)
        return node

    def visit_FunctionDef(self,node):
        node.name = self.names.get(node.name,node.name)
        return self.generic_visit(node)

    def visit_ClassDef(self,node):
        node.name = self.names.get(node.name,node.name)
        return self.generic_visit(node)


def build(candidate,out):
    if candidate not in ("one_job","prior_one_job"):
        raise ValueError("choose an actual forward-planning candidate")
    trees = []
    sources = {}
    for name,file,prefix in MODULES:
        path = Path(file)
        source = path.read_text(encoding="utf-8")
        sources[file] = hashlib.sha256(path.read_bytes()).hexdigest()
        tree = Flatten(source,file,prefix).visit(ast.parse(source))
        ast.fix_missing_locations(tree)
        trees.append(ast.unparse(tree))
    footer = '''
FUTURE_FEATURES = %s

class Agent(_bounded_BoundedAgent):
    def __init__(self, seed=0, params=None):
        super().__init__(seed, params, dict(FUTURE_FEATURES))

_AGENTS = {}

def act(state):
    try:
        seat = state.bot_id
    except Exception:
        return "STAY"
    player = _AGENTS.get(seat)
    if player is None:
        player = Agent(seed=seat * 7919)
        _AGENTS[seat] = player
    return player(state)
''' % repr(REGISTRY[candidate])
    source = '"""Zone Rush: self-contained conditional future planner.\nGenerated by futurelab/build.py; standard library only.\n"""\n\n'+"\n\n".join(trees)+footer
    tree = ast.parse(source)
    imports = {a.name.split(".")[0] for n in ast.walk(tree) if isinstance(n,ast.Import) for a in n.names}
    imports |= {n.module.split(".")[0] for n in ast.walk(tree) if isinstance(n,ast.ImportFrom)}
    if not imports <= {"random","time","collections","math"}:
        raise AssertionError(imports)
    if any(isinstance(n,ast.Call) and isinstance(n.func,ast.Name) and n.func.id in ("exec","eval","compile","__import__") for n in ast.walk(tree)):
        raise AssertionError("dynamic execution is not part of the submission")
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(source,encoding="utf-8",newline="\n")
    return dict(candidate=candidate,features=REGISTRY[candidate],sources=sources,
                sha256=hashlib.sha256(out.read_bytes()).hexdigest(),imports=sorted(imports))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidate",required=True,choices=REGISTRY)
    ap.add_argument("--out",type=Path,default=Path("futurelab/submission/bot.py"))
    args = ap.parse_args()
    result = build(args.candidate,args.out)
    args.out.with_suffix(".manifest.json").write_text(json.dumps(result,indent=2),encoding="utf-8",newline="\n")
    print(json.dumps(result,indent=2))


if __name__ == "__main__":
    main()
